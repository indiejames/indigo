package client

import (
	"fmt"
	"sort"
	"strings"
)

// DumpKeybindsTOML returns a commented-out [[keybind]] TOML skeleton
// listing every built-in action, grouped by category, generated from the
// same source the help popup reads (help_gen.go) — so it can't drift the
// way a hand-written reference doc would as actions get added. Exported
// for cmd/indigo's --dump-keybinds flag.
//
// Covers built-in actions only. Plugins bind no keys: their actions are
// listed in the Command (space) menu, under the keys each plugin's manifest
// gives them.
func DumpKeybindsTOML() string {
	var b strings.Builder
	b.WriteString("# Available actions for [[keybind]] overrides.\n")
	b.WriteString("# Generated by `indigo --dump-keybinds` from indigo's built-in keymap —\n")
	b.WriteString("# do not hand-edit this file; re-run to regenerate after upgrading indigo.\n")
	b.WriteString("# Uncomment a block and set `key` to bind it. A key that types a character\n")
	b.WriteString("# can't be bound. Plugin actions aren't listed here — they're in the\n")
	b.WriteString("# Command (Ctrl+Space) menu.\n\n")

	listed := map[string]bool{}
	writeBlock := func(label, defaults, key, name string) {
		listed[name] = true
		if defaults != "" {
			fmt.Fprintf(&b, "# %s — default key: %s\n", label, defaults)
		} else {
			fmt.Fprintf(&b, "# %s\n", label)
		}
		b.WriteString("# [[keybind]]\n")
		fmt.Fprintf(&b, "# key = %q\n", key)
		fmt.Fprintf(&b, "# action = %q\n\n", name)
	}
	writeSections := func(rows []*treeHelpRow, suffix string, keyOf func(*treeHelpRow) string) {
		byCategory := map[string][]*treeHelpRow{}
		for _, row := range rows {
			if !listed[row.name] {
				byCategory[row.category] = append(byCategory[row.category], row)
			}
		}
		for _, cat := range orderedCategories(byCategory) {
			fmt.Fprintf(&b, "# --- %s%s ---\n", cat, suffix)
			for _, row := range byCategory[cat] {
				writeBlock(row.label, strings.Join(row.seqs, " / "), keyOf(row), row.name)
			}
		}
	}

	// The keymap's own bindings, with the key each one has now.
	writeSections(collectHelpRows(defaultInsertCmds), "", func(row *treeHelpRow) string { return row.rawKeys[0] })
	// Actions reached through the Command menu: a menu key is a character,
	// so the placeholder is empty rather than one that would be refused.
	writeSections(collectHelpRows([]command{commandMenuRoot}), " (Command menu)", func(*treeHelpRow) string { return "" })

	// Everything else the palette can run.
	var rest []string
	for name := range exActionRegistry() {
		if !listed[name] {
			rest = append(rest, name)
		}
	}
	sort.Strings(rest)
	display := mergeDisplayInfo(canonicalDisplayInfo(defaultPrefixCmds), exOnlyDisplay)
	b.WriteString("# --- No default key (bind one to use it as a keypress) ---\n")
	for _, name := range rest {
		label := display[name].label
		if label == "" {
			label = name
		}
		writeBlock(label, "", "", name)
	}

	return b.String()
}

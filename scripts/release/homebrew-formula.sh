#!/bin/sh
# Print the Homebrew formula for a release.
#
#   scripts/release/homebrew-formula.sh <version-tag> <checksums.txt> > indigo.rb
#
# The release workflow pushes the result to the tap repository
# (indiejames/homebrew-tap, Formula/indigo.rb), which is what makes
# `brew install indiejames/tap/indigo` work.
set -eu

tag=${1:?usage: homebrew-formula.sh <version-tag> <checksums.txt>}
sums=${2:?usage: homebrew-formula.sh <version-tag> <checksums.txt>}
repo=${GITHUB_REPOSITORY:-indiejames/indigo}

sha() {
	s=$(awk -v f="indigo-$tag-$1.tar.gz" '$2 == f { print $1 }' "$sums")
	[ -n "$s" ] || { echo "no checksum for indigo-$tag-$1.tar.gz in $sums" >&2; exit 1; }
	echo "$s"
}
url() {
	echo "https://github.com/$repo/releases/download/$tag/indigo-$tag-$1.tar.gz"
}

darwin_arm64=$(sha darwin-arm64)
darwin_amd64=$(sha darwin-amd64)
linux_arm64=$(sha linux-arm64)
linux_amd64=$(sha linux-amd64)

cat <<EOF
# Generated by scripts/release/homebrew-formula.sh in $repo — do not edit by hand.
class Indigo < Formula
  desc "Modal terminal text editor with built-in language server support"
  homepage "https://github.com/$repo"
  version "${tag#v}"
  license "MIT"

  on_macos do
    on_arm do
      url "$(url darwin-arm64)"
      sha256 "$darwin_arm64"
    end
    on_intel do
      url "$(url darwin-amd64)"
      sha256 "$darwin_amd64"
    end
  end

  on_linux do
    on_arm do
      url "$(url linux-arm64)"
      sha256 "$linux_arm64"
    end
    on_intel do
      url "$(url linux-amd64)"
      sha256 "$linux_amd64"
    end
  end

  def install
    bin.install "indigo"
    # The static Linux servers indigo copies into dev containers. libexec keeps
    # them off PATH; indigo finds them by following bin/indigo's symlink.
    libexec.install Dir["indigo-server-linux-*"]
  end

  def caveats
    <<~EOS
      The bundled plugins (git, jumpy, bookmarks, spell, ...) are not installed
      by Homebrew. To add them to ~/.config/indigo/plugins:
        curl -fsSL https://raw.githubusercontent.com/$repo/main/install.sh | sh -s -- --plugins-only

      After upgrading, a server started by the old version keeps running until
      its last window closes. indigo warns when it connects to one; close every
      window for that workspace to pick up the new version.
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/indigo --version")
  end
end
EOF
